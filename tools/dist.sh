#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# tools/dist.sh - concatenate the modules into one standalone script
#
# Usage: tools/dist.sh OUTPUT
#
# The module list is read from KREUZER_MODULES in main.sh, so there is a single
# place to maintain it. main.sh goes first because modules read $APP while they
# load; KREUZER_BUNDLED makes it skip its own loading loop.

set -euo pipefail

root=$(cd "${BASH_SOURCE[0]%/*}/.." && pwd)
lib=$root/lib/kreuzer
out=${1:?usage: dist.sh OUTPUT}

mapfile -t modules < <(awk '
  /^KREUZER_MODULES=\(/ { f = 1; next }
  f && /^\)/ { exit }
  f { for (i = 1; i <= NF; i++) print $i }' "$lib/main.sh")
((${#modules[@]})) || { echo "dist: no modules found in main.sh" >&2; exit 1; }

version=$(sed -n 's/^VERSION="\(.*\)"$/\1/p' "$lib/main.sh")

# The bundle carries one header, so per-file ones are dropped. grep exits 1 on
# an empty result, which is not an error here.
strip() { grep -vE '^# (shellcheck shell=bash|SPDX-License-Identifier:)' "$1" || true; }

mkdir -p "$(dirname -- "$out")"
{
  echo '#!/usr/bin/env bash'
  echo '# SPDX-License-Identifier: GPL-3.0-or-later'
  echo "# kreuzer $version - single-file build generated by tools/dist.sh. Do not edit."
  echo 'KREUZER_BUNDLED=1'
  strip "$lib/main.sh"
  for m in "${modules[@]}"; do
    [[ -r $lib/$m.sh ]] || { echo "dist: missing module $m.sh" >&2; exit 1; }
    printf '\n# ---- %s ----\n' "$m"
    strip "$lib/$m.sh"
  done
  echo
  echo 'if [[ ${BASH_SOURCE[0]} == "$0" ]]; then main "$@"; exit $?; fi'
} >"$out"

chmod +x "$out"
# A syntax error in any module would otherwise only show up when the bundle runs.
bash -n "$out"
